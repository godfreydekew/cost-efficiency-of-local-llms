
import re
import time
import torch
from typing import Dict, List, Optional, Tuple, Set, Any


def build_system_prompt(label_names: Dict[int, str], examples: Optional[List[Dict[str, Any]]] = None) -> str:
    """
    Constructs a structured system prompt containing a numbered list of categories
    and optional few-shot reference exemplars.
    
    Args:
        label_names: Dict mapping label integer IDs to category string names {0: 'sadness', 1: 'joy', ...}
        examples: Optional list of dicts [{'text': ..., 'label': int}] for few-shot learning
        
    Returns:
        Formatted system prompt string.
    """
    # Build numbered class list
    class_list = '\n'.join(
        f'{idx}: {name}' 
        for idx, name in label_names.items()
    )
    
    # Build few-shot block if examples are provided
    if examples:
        example_lines = []
        for ex in examples:
            label_name = label_names[ex['label']]
            example_lines.append(
                f'Input Text: "{ex["text"]}"\n'
                f'Category Number: {ex["label"]}  ({label_name})'
            )
        few_shot_block = (
            "Here is one reference example per category to guide your classification:\n\n"
            + '\n\n'.join(example_lines)
            + '\n\n'
        )
    else:
        few_shot_block = ''
    
    return f"""You are a precise text classification engine.
Classify the input text into exactly one of the following categories:

{class_list}

Strict output rules:
1. Respond ONLY with the category number (e.g. 0, 1, 2).
2. Do NOT write any explanation, category name, or punctuation.
3. Your entire response must be a single integer.

{few_shot_block}"""


def build_user_message(text: str) -> str:
    """
    Formats the user message containing the target input text.
    """
    return f'Input Text: "{text}"\nCategory Number:'


def parse_prediction(raw_output: str, valid_labels: Set[int]) -> Tuple[int, bool]:
    """
    Parses the model's raw string response into a valid category integer label ID.
    
    Args:
        raw_output: Raw text output generated by the LLM.
        valid_labels: Set of valid category integer IDs (e.g., {0, 1, 2, 3}).
        
    Returns:
        Tuple of (predicted_label, parse_success):
        - Primary parse (exact int match): returns (pred, True)
        - Fallback parse (regex extraction of first integer): returns (pred, False)
        - Complete failure: returns (-1, False)
    """
    text = raw_output.strip()
    
    # Primary: direct integer parse (strict instruction compliance)
    try:
        pred = int(text)
        if pred in valid_labels:
            return pred, True
    except ValueError:
        pass
    
    # Fallback: extract first integer from response using regex
    match = re.search(r'\b(\d+)\b', text)
    if match:
        pred = int(match.group(1))
        if pred in valid_labels:
            return pred, False  # False indicates fallback was required
            
    # Complete failure: unparseable output or out-of-range label ID
    return -1, False


def extract_few_shot_examples(
    raw_dataset, 
    label_names: Dict[int, str], 
    text_col: str = "text", 
    label_col: str = "label", 
    seed: int = 42
) -> List[Dict[str, Any]]:
    """
    Extracts exactly 1 reference example per class from the training split
    to form balanced few-shot exemplars.
    """
    train_ds = raw_dataset['train']
    examples = []
    
    for label_id in sorted(label_names.keys()):
        # Filter samples matching current label
        matching_samples = train_ds.filter(lambda ex: ex[label_col] == label_id)
        if len(matching_samples) > 0:
            # Shuffle deterministically and pick the first sample
            shuffled = matching_samples.shuffle(seed=seed)
            selected = shuffled[0]
            examples.append({
                'text': selected[text_col],
                'label': selected[label_col]
            })
            
    return examples


def classify_gpt(
    text: str, 
    label_names: Dict[int, str], 
    examples: Optional[List[Dict[str, Any]]] = None, 
    client = None, 
    model: str = "gpt-4o"
) -> Tuple[str, int, int, int, float]:
    """
    Executes a single Zero-Shot or Few-Shot classification call via OpenAI API.
    
    Returns:
        Tuple of (raw_output, input_tokens, output_tokens, total_tokens, cost_usd)
    """
    system_prompt = build_system_prompt(label_names, examples)
    user_message  = build_user_message(text)
    
    response = client.chat.completions.create(
        model=model,
        messages=[
            {'role': 'system',  'content': system_prompt},
            {'role': 'user',    'content': user_message},
        ],
        max_tokens=3,
        temperature=0.0,
        top_p=1.0,
    )

    # response = client.responses.create(
    #     model=model,
    #     input=[
    #         {'role': 'system',  'content': system_prompt},
    #         {'role': 'user',    'content': user_message},
    #     ],
    #     text={"verbosity":"low"},
    #     reasoning={"effort": "low"}
    # )
    
    raw_output = response.choices[0].message.content.strip()
    input_tokens = response.usage.prompt_tokens
    output_tokens = response.usage.completion_tokens
    total_tokens = response.usage.total_tokens

    # raw_output = response.output_text.strip()
    # input_tokens = response.usage.input_tokens
    # output_tokens = response.usage.output_tokens
    # total_tokens = response.usage.total_tokens
    
    # Cost calculation: $0.25 per 1M input tokens, $2.00 per 1M output tokens
    cost_usd = (input_tokens * (2.50 / 1_000_000)) + (output_tokens * (10.00 / 1_000_000))
    
    return raw_output, input_tokens, output_tokens, total_tokens, cost_usd


def classify_llama(
    text: str, 
    label_names: Dict[int, str], 
    examples: Optional[List[Dict[str, Any]]] = None, 
    model = None, 
    tokenizer = None
) -> Tuple[str, int, int, int, float]:
    """
    Executes a single Zero-Shot or Few-Shot classification call using local Llama via Transformers.
    
    Note: temperature is set to None when do_sample=False to prevent Transformers warnings
    and ensure deterministic greedy decoding.
    
    Returns:
        Tuple of (raw_output, input_tokens, output_tokens, total_tokens, gen_time_s)
    """
    system_prompt = build_system_prompt(label_names, examples)
    user_message  = build_user_message(text)
    
    messages = [
        {'role': 'system',  'content': system_prompt},
        {'role': 'user',    'content': user_message},
    ]
    
    inputs = tokenizer.apply_chat_template(
        messages,
        return_tensors='pt',
        add_generation_prompt=True,
    )
    
    # Extract tensor input_ids if apply_chat_template returns a BatchEncoding / dict
    if isinstance(inputs, torch.Tensor):
        input_ids = inputs.to(model.device)
    elif hasattr(inputs, 'input_ids'):
        input_ids = inputs.input_ids.to(model.device)
    else:
        input_ids = inputs['input_ids'].to(model.device)
        
    input_tokens = input_ids.shape[1]
    
    t0 = time.time()
    with torch.no_grad():
        output_ids = model.generate(
            input_ids,
            max_new_tokens=3,
            temperature=None,   # Omitting temperature for greedy decoding (do_sample=False)
            do_sample=False,
            pad_token_id=tokenizer.pad_token_id,
        )
    gen_time = time.time() - t0
    
    # Extract only new generated output tokens
    new_tokens = output_ids[0][input_tokens:]
    output_tokens = len(new_tokens)
    total_tokens = input_tokens + output_tokens
    
    raw_output = tokenizer.decode(new_tokens, skip_special_tokens=True).strip()
    
    return raw_output, input_tokens, output_tokens, total_tokens, gen_time
